#!/usr/bin/env node
/**
 * Keeps lib/i18n/translated-pages.ts in step with the files in content/i18n.
 *
 * That map says which languages each page is published in. It has to be a
 * checked-in module rather than a directory read, because the language switcher
 * runs in the browser and needs the same answer the server used.
 *
 * Run: node scripts/sync-translations.mjs          (rewrite the map)
 *      node scripts/sync-translations.mjs --check  (fail if it is stale)
 */
import fs from "node:fs";
import path from "node:path";

const CONTENT_DIR = path.join("content", "i18n");
const OUT_FILE = path.join("lib", "i18n", "translated-pages.ts");

// Page keys, in the order lib/i18n/pages.ts declares them. "site" is the shared
// chrome rather than a page, so it is not listed.
const PAGE_KEYS = [
  "home",
  "privacy",
  "terms",
  "contact",
  "consultancy",
  "products",
  "tools",
  "calculators",
];

// The switcher's language order, so the generated arrays read the way the UI does.
const LANGUAGE_ORDER = [
  "hi",
  "bn",
  "ta",
  "te",
  "mr",
  "gu",
  "kn",
  "ml",
  "pa",
  "es",
  "fr",
  "ar",
  "pt",
  "id",
  "de",
  "zh",
];

function localesFor(key) {
  const dir = path.join(CONTENT_DIR, key);
  if (!fs.existsSync(dir)) return [];
  const present = new Set(
    fs
      .readdirSync(dir)
      .filter((file) => file.endsWith(".json"))
      .map((file) => file.replace(/\.json$/, "")),
  );
  return LANGUAGE_ORDER.filter((lang) => present.has(lang));
}

const entries = PAGE_KEYS.map((key) => [key, localesFor(key)]);

// Pages that also have a page per item — one per calculator, one per tool.
const ITEM_PAGES = ["calculators", "tools"];
const PAGE_PATHS_FOR_ITEMS = { calculators: "/calculators", tools: "/tools" };

/**
 * Whether an item's own page has been translated, as opposed to just its card
 * on the listing.
 *
 * The listing needs a name and a one-line description; the item's page needs
 * the copy a search engine indexes. Requiring the title, the description and
 * the headline — plus the explainer and the FAQ wherever English has them —
 * keeps a half-translated page from being published and then competing with
 * the English one it was meant to serve alongside.
 */
function itemIsTranslated(english, translated) {
  if (!translated) return false;
  const has = (o, ...keys) =>
    keys.every((k) => typeof o?.[k] === "string" && o[k].trim() !== "");

  if (!has(translated.seo, "title", "description")) return false;
  if (!has(translated.hero, "headline", "subheadline")) return false;

  if (
    english.about &&
    !(translated.about?.paragraphs?.length === english.about.paragraphs.length)
  )
    return false;
  if (
    english.faq &&
    !(translated.faq?.items?.length === english.faq.items.length)
  )
    return false;

  return true;
}

function translatedItems(key) {
  const englishFile = path.join("content", "en", `${key}.json`);
  if (!fs.existsSync(englishFile)) return [];
  const english = JSON.parse(fs.readFileSync(englishFile, "utf8")).items ?? [];

  const byLang = new Map();
  for (const lang of localesFor(key)) {
    const file = path.join(CONTENT_DIR, key, `${lang}.json`);
    byLang.set(lang, JSON.parse(fs.readFileSync(file, "utf8")).items ?? []);
  }

  return english
    .filter(
      (item) =>
        !item.href || item.href === `${PAGE_PATHS_FOR_ITEMS[key]}/${item.slug}`,
    )
    .map((item) => [
      item.slug,
      LANGUAGE_ORDER.filter((lang) => {
        const items = byLang.get(lang);
        if (!items) return false;
        const index = english.findIndex((x) => x.slug === item.slug);
        return itemIsTranslated(item, items[index]);
      }),
    ]);
}

const itemEntries = ITEM_PAGES.map((key) => [key, translatedItems(key)]);

const itemBody = itemEntries
  .map(([key, items]) => {
    const rows = items
      .map(
        ([slug, locales]) =>
          `    "${slug}": [${locales.map((l) => `"${l}"`).join(", ")}],`,
      )
      .join("\n");
    return `  ${key}: {\n${rows}\n  },`;
  })
  .join("\n");

const body = entries
  .map(([key, locales]) => {
    if (locales.length === 0) return `  ${key}: [],`;
    return `  ${key}: [${locales.map((l) => `"${l}"`).join(", ")}],`;
  })
  .join("\n");

const generated = `// Generated by scripts/sync-translations.mjs — do not edit by hand.
//
// Which languages each page has been translated into, read from the files in
// content/i18n/<page>/<lang>.json. Checked in because the language switcher
// runs in the browser and has to agree with what the server published.

import type { LanguageCode } from "./config";
import type { PageKey } from "./pages";

export const TRANSLATED_PAGES: Record<PageKey, LanguageCode[]> = {
${body}
};

/**
 * Which languages each individual calculator and tool page is published in.
 *
 * Separate from TRANSLATED_PAGES because the directory of calculators can be
 * translated long before the twenty-nine pages it links to are, and a page is
 * only listed here once its own copy has been translated.
 */
export const TRANSLATED_ITEMS: Record<"calculators" | "tools", Record<string, LanguageCode[]>> = {
${itemBody}
};
`;

const current = fs.existsSync(OUT_FILE)
  ? fs.readFileSync(OUT_FILE, "utf8")
  : "";

if (process.argv.includes("--check")) {
  if (current !== generated) {
    console.error(
      "check-translations: lib/i18n/translated-pages.ts is out of date.\n" +
        "Run `npm run sync:translations` after adding or removing a translation file.",
    );
    process.exit(1);
  }
  const counts = entries.map(([key, l]) => `${key}=${l.length}`).join(" ");
  console.log(
    `check-translations: translated-pages.ts is current (${counts}).`,
  );
} else {
  fs.writeFileSync(OUT_FILE, generated);
  console.log(`sync-translations: wrote ${OUT_FILE}`);
  for (const [key, locales] of entries)
    console.log(`  ${key}: ${locales.length} languages`);
  for (const [key, items] of itemEntries) {
    const done = items.filter(([, l]) => l.length > 0).length;
    const full = items.filter(
      ([, l]) => l.length === LANGUAGE_ORDER.length,
    ).length;
    console.log(
      `  ${key} item pages: ${done}/${items.length} started, ${full} in all 16`,
    );
  }
}
